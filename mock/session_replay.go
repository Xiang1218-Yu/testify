package mock

import (
	"fmt"
	"sync"

	"github.com/stretchr/testify/assert"
)

// ReplayConfig configures a replay session.
type ReplayConfig struct {
	// Mocks are the mocks used for replay, in the same order (and with the
	// same names) as at record time.
	Mocks []interface{}
	// Names mirrors CallSessionConfig.Names.
	Names []string
	// T optionally reports replay divergences through a TestingT. When nil,
	// divergences panic with the structured *SessionError.
	T TestingT
}

// ReplaySession replays a sealed CallRecord against live mocks. Every
// incoming call is strictly verified against the next recorded top-level
// event: mock identity, method, arguments, count, cross-mock dependency
// order and nesting. Recorded Run callbacks, waits and other external side
// effects are never executed again; recorded panics and return arguments are
// reproduced.
type ReplaySession struct {
	version SessionVersion
	rec     *CallRecord
	t       TestingT

	mu       sync.Mutex
	finished bool
	result   error

	mocks  []*frozenMock
	byMock map[*Mock]*frozenMock

	// incoming holds the events the code under test must produce, i.e.
	// top-level events in Seq order. Events generated by Run callbacks are
	// intentionally excluded because their side effects are suppressed.
	incoming []*CallEvent
	cursor   int

	// open is the per-goroutine nesting depth during replay. Side-effect
	// free replay cannot nest calls, so any depth greater than zero is a
	// divergence.
	open map[int64]int
}

// sessionVersionInfo implements sessionController.
func (r *ReplaySession) sessionVersionInfo() SessionVersion { return r.version }

// StartReplay validates the sealed record (integrity, mock interfaces,
// expectation graph version), attaches the supplied mocks and starts replay.
// Records resumed from an interrupted, unsealed checkpoint cannot be
// replayed.
func StartReplay(rec *CallRecord, cfg ReplayConfig) (*ReplaySession, error) {
	if rec == nil {
		return nil, newSessionError(SessionErrorIntegrity, "replay", SessionVersion{Format: CallSessionFormat}, 0, -1, "",
			"nil record")
	}
	version := rec.Version
	if err := rec.Verify(); err != nil {
		return nil, asSessionError(err, SessionErrorIntegrity, "replay", version)
	}
	if !rec.Sealed {
		return nil, newSessionError(SessionErrorInvalidState, "replay", version, rec.Len(), -1, "",
			"only sealed records can be replayed; resume checkpoint records before committing them")
	}

	sessionRegistryMu.Lock()
	defer sessionRegistryMu.Unlock()

	fms, err := freezeMocks(cfg.Mocks, cfg.Names, version, "replay")
	if err != nil {
		return nil, err
	}
	if err := validateFrozenAgainstRecord(fms, rec, version, "replay", SessionErrorReplayDivergence); err != nil {
		detachSilently(fms, version)
		return nil, err
	}

	r := &ReplaySession{
		version: version,
		rec:     rec,
		t:       cfg.T,
		mocks:   fms,
		byMock:  make(map[*Mock]*frozenMock),
		open:    make(map[int64]int),
	}
	for _, ev := range rec.Events {
		if !ev.ViaRun {
			r.incoming = append(r.incoming, ev)
		}
	}
	for _, ev := range r.incoming {
		// Expectation panics are reproduced from the event text and never
		// carry return values. Every other event must have reached the
		// return-capture phase while recording; an exported record must
		// additionally carry a decodable value payload (a nil returns slice
		// itself is legitimate for Return() with zero arguments).
		if ev.Panic != "" {
			continue
		}
		if !ev.hasReturns || !ev.payloadPresent {
			detachSilently(fms, version)
			return nil, newSessionError(SessionErrorIntegrity, "replay", version, ev.Seq, ev.MockIndex, ev.MockName,
				"record does not carry live return values for this event; in-process records are replayable, exported records need a decodable value payload")
		}
	}

	for _, fm := range fms {
		r.byMock[fm.m] = fm
		fm.m.mutex.Lock()
		fm.m.session = r
		fm.m.mutex.Unlock()
	}
	return r, nil
}

// dispatch is invoked by Mock.MethodCalled while a replay session is
// attached.
func (r *ReplaySession) dispatch(m *Mock, methodName string, arguments []interface{}) Arguments {
	gid := goroutineID()

	r.mu.Lock()
	if r.finished {
		r.mu.Unlock()
		return m.methodCalledLegacy(methodName, arguments...)
	}
	fm := r.byMock[m]
	if fm == nil {
		err := newSessionError(SessionErrorConcurrentSession, "replay", r.version, r.nextPosition(), -1, "",
			"call routed into a replay session that does not own this mock")
		r.markFinishedLocked(err)
		r.mu.Unlock()
		r.detach()
		r.stop(m, err)
		return nil
	}
	if r.open[gid] > 0 {
		err := newSessionError(SessionErrorReplayDivergence, "replay", r.version, r.nextPosition(), fm.index, fm.name,
			fmt.Sprintf("unexpected nested call to %s: Run callbacks are suppressed during replay, no call can be open", methodName))
		r.markFinishedLocked(err)
		r.mu.Unlock()
		r.detach()
		r.stop(m, err)
		return nil
	}
	if r.cursor >= len(r.incoming) {
		err := newSessionError(SessionErrorReplayDivergence, "replay", r.version, r.nextPosition(), fm.index, fm.name,
			fmt.Sprintf("unexpected extra call to %s%v; all %d recorded call(s) already occurred", methodName, summarizeArguments(arguments), len(r.incoming)))
		r.markFinishedLocked(err)
		r.mu.Unlock()
		r.detach()
		r.stop(m, err)
		return nil
	}

	ev := r.incoming[r.cursor]
	detail := ""
	switch {
	case ev.MockIndex != fm.index:
		detail = fmt.Sprintf("wrong mock at event %d: recorded %q (%d), call arrived on %q (%d)",
			ev.Seq, ev.MockName, ev.MockIndex, fm.name, fm.index)
	case ev.Method != methodName:
		detail = fmt.Sprintf("wrong method at event %d on %s: recorded %q, got %q", ev.Seq, fm.name, ev.Method, methodName)
	case digestValues(arguments) != ev.argsDigest:
		detail = fmt.Sprintf("arguments of %s at event %d diverge from the recording:\nrecorded: %s\nactual:   %s",
			methodName, ev.Seq, ev.ArgsSummary, summarizeArguments(arguments))
	}
	if detail != "" {
		err := newSessionError(SessionErrorReplayDivergence, "replay", r.version, ev.Seq, fm.index, fm.name, detail)
		r.markFinishedLocked(err)
		r.mu.Unlock()
		r.detach()
		r.stop(m, err)
		return nil
	}
	r.cursor++
	r.open[gid]++
	r.mu.Unlock()

	defer func() {
		r.mu.Lock()
		r.open[gid]--
		if r.open[gid] <= 0 {
			delete(r.open, gid)
		}
		r.mu.Unlock()
	}()

	// Mirror the legacy expectation accounting (repeatability, totalCalls,
	// Calls slice) so post-replay AssertExpectations/AssertNumberOfCalls see
	// the same state, but never touch WaitFor/Run.
	call := r.mocks[ev.MockIndex].expects[ev.ExpectationIndex].ptr
	m.mutex.Lock()
	if call.Repeatability == 1 {
		call.Repeatability = -1
	} else if call.Repeatability > 1 {
		call.Repeatability--
	}
	call.totalCalls++
	m.Calls = append(m.Calls, *newCall(m, methodName, assert.CallerInfo(), arguments, ev.returns))
	m.mutex.Unlock()

	// Reproduce a recorded expectation panic (Run-callback panics belong to
	// suppressed Run-child events and are never reached here).
	if ev.Panic != "" && ev.PanicSource != "run" {
		panic(ev.Panic)
	}

	return ev.returns
}

func (r *ReplaySession) nextPosition() int {
	if r.cursor < len(r.incoming) {
		return r.incoming[r.cursor].Seq
	}
	if len(r.incoming) > 0 {
		return r.incoming[len(r.incoming)-1].Seq + 1
	}
	return 1
}

func (r *ReplaySession) markFinishedLocked(err error) {
	r.finished = true
	r.result = err
}

// stop halts the test through the configured TestingT (or the mock's own
// test handle), and otherwise panics with the structured error.
func (r *ReplaySession) stop(m *Mock, err *SessionError) {
	if r.t != nil {
		r.t.Errorf("%s", err.Error())
		r.t.FailNow()
		return
	}
	m.mutex.Lock()
	mt := m.test
	m.mutex.Unlock()
	if mt != nil {
		mt.Errorf("%s", err.Error())
		mt.FailNow()
		return
	}
	panic(err)
}

// detach removes the replay session from every mock it owns. Mocks found
// attached to a different session are left untouched; the first such finding
// is reported as cleanup failure.
func (r *ReplaySession) detach() *SessionError {
	var cleanupErr *SessionError
	for _, fm := range r.mocks {
		fm.m.mutex.Lock()
		switch {
		case fm.m.session == nil:
		case fm.m.session == r:
			fm.m.session = nil
		default:
			if cleanupErr == nil {
				cleanupErr = newSessionError(SessionErrorCleanupFailed, "cleanup", r.version, 0, fm.index, fm.name,
					"mock was attached to a different session during replay tear down; left that session untouched")
			}
		}
		fm.m.mutex.Unlock()
	}
	return cleanupErr
}

// Finish verifies that every recorded top-level call occurred in the recorded
// order, count and shape, detaches all mocks and returns the first divergence
// as a structured error. It is idempotent: repeated calls return the same
// result.
func (r *ReplaySession) Finish() error {
	r.mu.Lock()
	if r.finished {
		err := r.result
		r.mu.Unlock()
		return err
	}
	if r.cursor < len(r.incoming) {
		missing := r.incoming[r.cursor]
		err := newSessionError(SessionErrorReplayDivergence, "finish", r.version, missing.Seq, missing.MockIndex, missing.MockName,
			fmt.Sprintf("recorded call to %s.%s%v never happened during replay (%d of %d call(s) replayed)",
				missing.MockName, missing.Method, missing.ArgsSummary, r.cursor, len(r.incoming)))
		r.markFinishedLocked(err)
		r.mu.Unlock()
		if cleanupErr := r.detach(); cleanupErr != nil {
			return cleanupErr
		}
		return err
	}
	r.finished = true
	r.mu.Unlock()

	if cleanupErr := r.detach(); cleanupErr != nil {
		r.mu.Lock()
		r.result = cleanupErr
		r.mu.Unlock()
		return cleanupErr
	}
	return nil
}

// Close detaches the replay session without enforcing the remaining call
// count. It is safe to defer; Finish should be used for verification. It is
// idempotent: repeated calls (including a call after a divergence already
// tore the session down) return nil.
func (r *ReplaySession) Close() error {
	r.mu.Lock()
	if r.finished {
		r.mu.Unlock()
		return nil
	}
	r.finished = true
	r.mu.Unlock()
	if cleanupErr := r.detach(); cleanupErr != nil {
		return cleanupErr
	}
	return nil
}
